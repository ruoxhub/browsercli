import assert from 'node:assert/strict';
import {access, mkdtemp, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {describe, it} from 'node:test';

import {printNativeIgnitionBytecode} from '../../../../src/modules/v8-inspector/NativeBytecodePrinter.js';

describe('printNativeIgnitionBytecode', () => {
  it('does not execute captured page source without an explicit unsafe opt-in', async () => {
    const result = await printNativeIgnitionBytecode({
      functionName: 'add',
      sourceSlice: 'function add(left, right) { return left + right; }',
    });

    assert.equal(result.available, false);
    assert.match(result.reason, /unsafeExecuteCapturedSource/u);
  });

  it('extracts Ignition bytecode from an isolated V8 process', async () => {
    const result = await printNativeIgnitionBytecode(
      {
        functionName: 'add',
        sourceSlice: 'function add(left, right) { return left + right; }',
      },
      10_000,
      true,
    );

    assert.equal(result.available, true);
    assert.equal(result.format, 'ignition-bytecode');
    assert.equal(result.functionName, 'add');
    assert.equal(result.rawIgnitionBytecodeAvailable, true);
    assert.match(
      result.bytecode ?? '',
      /generated bytecode for function: add/u,
    );
  });

  it('reports source reconstruction failures without throwing', async () => {
    const result = await printNativeIgnitionBytecode(
      {functionName: 'broken', sourceSlice: '42'},
      5_000,
      true,
    );

    assert.equal(result.available, false);
    assert.equal(result.bytecode, null);
    assert.match(result.reason, /Unable to reconstruct/u);
  });

  it('denies host filesystem writes even after unsafe execution is opted in', async () => {
    const directory = await mkdtemp(
      join(tmpdir(), 'v8-bytecode-sandbox-test-'),
    );
    const marker = join(directory, 'should-not-exist.txt');
    try {
      await printNativeIgnitionBytecode(
        {
          functionName: 'probe',
          sourceSlice: `function probe() { require('node:fs').writeFileSync(${JSON.stringify(marker)}, 'unsafe'); }`,
        },
        10_000,
        true,
      );

      await assert.rejects(access(marker), {code: 'ENOENT'});
    } finally {
      await rm(directory, {recursive: true, force: true});
    }
  });
});
