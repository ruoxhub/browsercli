import type {CodeFile} from '../../types/index.js';

/** 单个缺失能力 */
export interface MissingCapability {
  capability: string;
  /** 匹配运行时错误的模式列表 */
  patterns: string[];
  reason: string;
  priority: number;
}

/** buildAutoBundle 的选项 */
export interface AutoBundleOptions {
  targetKeywords: string[];
  targetUrlPatterns: string[];
  targetFunctionNames: string[];
  targetActionDescription: string;
  maxEvidenceItems: number;
}

/** buildAutoBundle 的结果 */
export interface AutoBundleResult {
  entryCode: string;
  envCode: string;
  polyfillsCode: string;
  capture: Record<string, unknown>;
  notes: string[];
}

/** rebuild 工具统一响应结构（所有 rebuild/* 工具返回此格式） */
export interface RebuildToolResponse {
  success: boolean;
  message: string;
  tooltype: 'export_rebuild_bundle' | 'diff_env_requirements';
  data: RebuildToolData;
}

export interface RebuildToolData {
  taskId: string;
  taskDir: string;
  autoGenerated: boolean;
  files: string[];
  /** 可选的额外数据（diff_env_requirements 时填充） */
  missingCapabilities?: string[];
  nextPatches?: NextPatch[];
}

export interface NextPatch {
  capability: string;
  reason: string;
  suggestedPatch: string;
}
